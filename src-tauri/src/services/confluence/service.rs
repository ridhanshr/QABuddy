fn base64_encode(data: &[u8]) -> String {
    base64::engine::general_purpose::STANDARD.encode(data)
}

fn parse_tables_to_entries_with_progress<F: FnMut(usize, usize)>(
    content: &str,
    table_positions: Option<&[(usize, usize)]>,
    mut on_progress: F,
) -> Vec<ConfluenceTestImportEntry> {
    let mut entries: Vec<ConfluenceTestImportEntry> = Vec::new();
    let table_positions = table_positions
        .map(|positions| positions.to_vec())
        .unwrap_or_else(|| iter_table_positions(content));
    let total = table_positions.len();
    let row_re = RE_ROW.get_or_init(|| regex::Regex::new(r"(?is)<tr\b[^>]*>([\s\S]*?)</tr>").unwrap());
    let cell_re = RE_CELL.get_or_init(|| regex::Regex::new(r"(?is)<t[dh][^>]*>([\s\S]*?)</t[dh]>").unwrap());
    let th_re = RE_TH.get_or_init(|| regex::Regex::new(r"(?i)<th\b").unwrap());

    let mut counter = 1usize;
    let mut vertical_index = 0usize;
    for (idx, (start, end)) in table_positions.iter().enumerate() {
        let body = &content[*start..*end];
        on_progress(idx + 1, total);

        if is_vertical_table(body) {
            if let Some(mut entry) = parse_vertical_table(body, &mut counter) {
                entry.source_table_index = Some(vertical_index);
                vertical_index += 1;
                entries.push(entry);
            }
            continue;
        }

        let (header_map, has_header) = parse_header_map(body);
        for row_cap in row_re.captures_iter(body) {
            let row = &row_cap[1];
            if th_re.is_match(row) {
                continue;
            }
            let cells: Vec<String> = cell_re
                .captures_iter(row)
                .map(|c| c[1].to_string())
                .collect();
            if cells.iter().all(|c| strip_inner_tags(c).trim().is_empty()) {
                continue;
            }
            let entry = build_entry(&cells, &header_map, has_header, &mut counter);
            entries.push(entry);
        }
    }

    entries
}

/// Extract the plain-text value of a named field row in a vertical-card table.
/// Exact case-insensitive match on the trimmed label text.
fn extract_vertical_cell(table_html: &str, field: &str) -> Option<String> {
    for (_rs, _re, inner_start, inner_end) in iter_tr_positions(table_html) {
        let row_inner = &table_html[inner_start..inner_end];
        let cells = split_row_cells(row_inner);
        if cells.len() < 2 { continue; }
        let label = strip_inner_tags(&cells[0]).trim().to_lowercase();
        if label == field {
            return Some(strip_inner_tags(&cells[1]).trim().to_string());
        }
    }
    None
}

/// Replace the value cell (second `<td>`) of a named field row in a vertical-card table.
/// Exact case-insensitive match on the trimmed label text of the first cell.
///
/// Uses depth-tracking iterators (not naive regex) so nested tables and AC macros
/// that contain `</tr>` or `</td>` inside them are handled correctly.
fn replace_vertical_cell_value(table_html: &str, field: &str, new_value: &str) -> String {
    for (_row_start, _row_end, row_inner_start, row_inner_end)
        in iter_tr_positions(table_html)
    {
        let row_inner = &table_html[row_inner_start..row_inner_end];
        let cells = split_row_cells(row_inner);
        if cells.len() < 2 { continue; }

        let label = strip_inner_tags(&cells[0]).trim().to_lowercase();
        if label != field { continue; }

        // Found the right row — now splice the new value into the second cell.
        if let Some((cell_open, inner_start, inner_end, cell_end))
            = find_second_cell_positions(row_inner)
        {
            // cell positions are all relative to row_inner
            let open_tag  = &row_inner[cell_open..inner_start];
            let close_tag = &row_inner[inner_end..cell_end];
            let new_row_inner = format!(
                "{}{}{}{}{}",
                &row_inner[..cell_open],
                open_tag,
                new_value,
                close_tag,
                &row_inner[cell_end..],
            );
            let mut result = table_html.to_string();
            result.replace_range(row_inner_start..row_inner_end, &new_row_inner);
            return result;
        }
        break; // found the row but cell parse failed — leave unchanged
    }

    table_html.to_string()
}

/// Iterate top-level `<table>…</table>` blocks in `html` using depth tracking,
/// yielding `(start, end)` byte positions. Nested tables (inside macros or cells)
/// are skipped — only the outermost `<table>` boundaries are returned.
fn iter_table_positions(html: &str) -> Vec<(usize, usize)> {
    let open_re  = regex::Regex::new(r"(?i)<table\b[^>]*>").unwrap();
    let close_re = regex::Regex::new(r"(?i)</table>").unwrap();
    let len = html.len();
    let mut results = Vec::new();
    let mut pos = 0usize;

    while pos < len {
        let Some(open_m) = open_re.find(&html[pos..]) else { break };
        let tbl_start = pos + open_m.start();
        let mut depth = 1i32;
        let mut cur = pos + open_m.end();

        while cur < len && depth > 0 {
            let rest = &html[cur..];
            let next_open  = open_re.find(rest).map(|m| m.start());
            let next_close = close_re.find(rest).map(|m| (m.start(), m.end()));
            match (next_open, next_close) {
                (Some(o), Some((c, _))) if o < c => {
                    depth += 1;
                    cur += open_re.find(rest).unwrap().end();
                }
                (_, Some((_, ce))) => {
                    depth -= 1;
                    cur += ce;
                    if depth == 0 {
                        results.push((tbl_start, cur));
                        pos = cur;
                        break;
                    }
                }
                _ => { pos = len; break; }
            }
        }
        if depth > 0 { break; }
    }
    results
}

/// Iterate `<tr>…</tr>` blocks in `html`, yielding
/// `(row_start, row_end, inner_start, inner_end)` where the inner span
/// does **not** include the opening `<tr…>` or closing `</tr>` tag.
/// Depth-tracks nested `<tr>` so that tables-within-tables are handled
/// (Confluence Expand macros can embed arbitrary content).
fn iter_tr_positions(html: &str) -> Vec<(usize, usize, usize, usize)> {
    let open_re  = regex::Regex::new(r"(?i)<tr\b[^>]*>").unwrap();
    let close_re = regex::Regex::new(r"(?i)</tr>").unwrap();
    let len = html.len();
    let mut results = Vec::new();
    let mut pos = 0usize;

    while pos < len {
        let Some(open_m) = open_re.find(&html[pos..]) else { break };
        let tr_start      = pos + open_m.start();
        let inner_start   = pos + open_m.end();
        let mut depth = 1i32;
        let mut cur = inner_start;

        while cur < len && depth > 0 {
            let rest = &html[cur..];
            let next_open  = open_re.find(rest).map(|m| m.start());
            let next_close = close_re.find(rest).map(|m| m.start());
            match (next_open, next_close) {
                (Some(o), Some(c)) if o < c => {
                    depth += 1;
                    cur += open_re.find(rest).unwrap().end();
                }
                (_, Some(c)) => {
                    depth -= 1;
                    let close_end = cur + close_re.find(rest).unwrap().end();
                    if depth == 0 {
                        results.push((tr_start, close_end, inner_start, cur + c));
                        cur = close_end;
                        pos = cur;
                        break;
                    }
                    cur = close_end;
                }
                _ => { pos = len; break; }
            }
        }
        if depth > 0 { break; }
    }
    results
}

/// Within a row's inner HTML find the second `<t[dh]…>…</t[dh]>` cell using
/// depth-tracking, and return `(cell_open_start, inner_start, inner_end, cell_end)`.
/// All positions are relative to `row_inner`.
fn find_second_cell_positions(row_inner: &str) -> Option<(usize, usize, usize, usize)> {
    let open_re  = regex::Regex::new(r"(?i)<t[dh]\b[^>]*>").unwrap();
    let close_re = regex::Regex::new(r"(?i)</t[dh]>").unwrap();
    let len = row_inner.len();
    let mut cell_idx = 0usize;
    let mut pos = 0usize;

    while pos < len {
        let Some(open_m) = open_re.find(&row_inner[pos..]) else { break };
        let cell_open_start = pos + open_m.start();
        let inner_start     = pos + open_m.end();
        let mut depth = 1i32;
        let mut cur = inner_start;

        while cur < len && depth > 0 {
            let rest = &row_inner[cur..];
            let next_open  = open_re.find(rest).map(|m| m.start());
            let next_close = close_re.find(rest).map(|m| m.start());
            match (next_open, next_close) {
                (Some(o), Some(c)) if o < c => {
                    depth += 1;
                    cur += open_re.find(rest).unwrap().end();
                }
                (_, Some(c)) => {
                    depth -= 1;
                    let close_end = cur + close_re.find(rest).unwrap().end();
                    if depth == 0 {
                        cell_idx += 1;
                        if cell_idx == 2 {
                            return Some((cell_open_start, inner_start, cur + c, close_end));
                        }
                        pos = close_end;
                        break;
                    }
                    cur = close_end;
                }
                _ => return None,
            }
        }
        if depth > 0 { break; }
    }
    None
}

/// Sanitize existing Confluence page content so that every `<td>`/`<th>` whose
/// content starts with bare inline elements (`<strong>`, `<span>`, `<em>`, `<a>`,
/// `<code>`, etc.) — i.e. NOT already wrapped in a block-level element — gets
/// the whole cell content wrapped in a `<p>…</p>`.
///
/// This is needed because old content (created before our XHTML fix) may have
/// cells like `<td><strong>PASS</strong></td>` which Confluence rejects when we
/// write the page back.
fn sanitize_td_inline_content(html: &str) -> String {
    // Inline-only tags that need wrapping when they appear at the top of a cell
    let inline_tag_re = regex::Regex::new(
        r"(?i)^<(strong|em|span|a|code|s|u|sub|sup|b|i)\b"
    ).unwrap();
    // Block-level tags — if the content starts with one of these, no wrapping needed
    let block_tag_re = regex::Regex::new(
        r"(?i)^<(p|ol|ul|li|h[1-6]|table|tbody|tr|th|td|div|ac:|ri:|blockquote|pre)\b"
    ).unwrap();

    let open_re  = regex::Regex::new(r"(?i)<t[dh]\b[^>]*>").unwrap();
    let close_re = regex::Regex::new(r"(?i)</t[dh]>").unwrap();
    let len = html.len();
    let mut result = String::with_capacity(html.len() + 256);
    let mut pos = 0usize;

    while pos < len {
        let Some(open_m) = open_re.find(&html[pos..]) else {
            result.push_str(&html[pos..]);
            break;
        };
        // Copy everything up to and including the opening tag
        let _open_abs_start = pos + open_m.start();
        let open_abs_end    = pos + open_m.end();
        result.push_str(&html[pos..open_abs_end]);

        // Depth-track to find the matching close tag
        let inner_start = open_abs_end;
        let mut depth = 1i32;
        let mut cur = inner_start;
        let mut inner_end = inner_start;
        let mut cell_end = inner_start;

        while cur < len && depth > 0 {
            let rest = &html[cur..];
            let next_open  = open_re.find(rest).map(|m| m.start());
            let next_close = close_re.find(rest).map(|m| (m.start(), m.end()));
            match (next_open, next_close) {
                (Some(o), Some((c, _))) if o < c => {
                    depth += 1;
                    cur += open_re.find(rest).unwrap().end();
                }
                (_, Some((c, ce))) => {
                    depth -= 1;
                    if depth == 0 {
                        inner_end = cur + c;
                        cell_end  = cur + ce;
                        break;
                    }
                    cur += ce;
                }
                _ => { break; }
            }
        }

        if depth > 0 {
            // Unclosed cell — just copy the rest as-is
            result.push_str(&html[open_abs_end..]);
            break;
        }

        let inner = &html[inner_start..inner_end];
        let close_tag = &html[inner_end..cell_end];
        let trimmed = inner.trim();

        let needs_wrap = if trimmed.is_empty() {
            false
        } else if trimmed.starts_with('<') {
            // Starts with a tag — inline if matched by inline_tag_re, needs wrap
            // Block if matched by block_tag_re, no wrap needed
            inline_tag_re.is_match(trimmed) && !block_tag_re.is_match(trimmed)
        } else {
            // Starts with plain text — always needs a <p> wrapper
            true
        };

        if needs_wrap {
            result.push_str("<p>");
            result.push_str(trimmed);
            result.push_str("</p>");
        } else {
            result.push_str(inner);
        }
        result.push_str(close_tag);
        pos = cell_end;
    }

    result
}

/// Sanitize Confluence storage-format HTML fetched from an existing page so that
/// the content can be safely written back via the REST API without a 400 error.
///
/// Problems this handles:
/// 1. Unknown / non-Confluence XML tags (`<xml>`, `<o:p>`, `<w:...>`, `<v:...>`,
///    `<m:...>`, `<x:...>`, etc.) left over from pasted Office/Word content —
///    strip the tag itself but keep the inner text.
/// 2. Orphan close tags (`</div>`, `</xml>`, `</span>` etc.) that have no
///    matching open tag — remove them.
/// 3. Unclosed inline tags (`<strong>`, `<em>`, …) at block boundaries —
///    handled by `close_unclosed_inline_tags` which is called after this.
fn sanitize_confluence_storage_html(html: &str) -> String {
    // ── Step 1: strip Office/Word XML namespace tags entirely (open + close) ──
    // These are tags like <xml>, <o:p>, <w:sdtPr>, <v:shape>, <m:math> etc.
    // We remove the tag but keep any text content inside.
    // Also remove XML processing instructions: <?xml ...?> and <!...>
    let office_tag_re = regex::Regex::new(
        r"(?i)</?(?:xml|o:[a-z0-9]+|w:[a-z0-9]+|v:[a-z0-9]+|m:[a-z0-9]+|x:[a-z0-9]+)[^>]*/?>"
    ).unwrap();
    let pi_re = regex::Regex::new(r"(?i)<\?xml[^?]*\?>|<![A-Za-z][^>]*>").unwrap();
    let mut out = office_tag_re.replace_all(html, "").to_string();
    out = pi_re.replace_all(&out, "").to_string();

    // ── Step 2: track open/close counts for block-level tags and remove
    //    orphan close tags (close tags with no matching open tag) ──────────
    // We only track the tags that Confluence commonly complains about.
    const BLOCK_TAGS: &[&str] = &["div", "section", "article", "header", "footer", "nav", "aside"];
    out = remove_orphan_close_tags(&out, BLOCK_TAGS);

    out
}

/// Remove close tags (e.g. `</div>`) that have no corresponding open tag.
/// Uses a running depth counter: whenever a close tag is encountered with
/// depth == 0 (no matching open tag seen yet), that close tag is dropped.
fn remove_orphan_close_tags(html: &str, tags: &[&str]) -> String {
    let mut out = html.to_string();
    for tag in tags {
        let open_re  = regex::Regex::new(&format!(r"(?i)<{tag}\b[^>]*>")).unwrap();
        let close_re = regex::Regex::new(&format!(r"(?i)</{tag}>")).unwrap();

        // Build sorted event list: (pos, end, is_close)
        let mut events: Vec<(usize, usize, bool)> = Vec::new();
        for m in open_re.find_iter(&out)  { events.push((m.start(), m.end(), false)); }
        for m in close_re.find_iter(&out) { events.push((m.start(), m.end(), true));  }
        events.sort_by_key(|e| e.0);

        // Walk events; collect positions of orphan close tags to remove
        let mut depth = 0i32;
        let mut orphans: Vec<(usize, usize)> = Vec::new();
        for (pos, end, is_close) in &events {
            if *is_close {
                if depth == 0 {
                    orphans.push((*pos, *end));
                } else {
                    depth -= 1;
                }
            } else {
                depth += 1;
            }
        }

        if orphans.is_empty() { continue; }

        // Rebuild string skipping orphan ranges
        let mut result = String::with_capacity(out.len());
        let mut cursor = 0usize;
        for (start, end) in &orphans {
            result.push_str(&out[cursor..*start]);
            cursor = *end;
        }
        result.push_str(&out[cursor..]);
        out = result;
    }
    out
}

/// Remove orphan close tags for both block and inline tags.
/// An orphan close tag is one with no matching open tag before it in the document.
fn close_unclosed_inline_tags(html: &str) -> String {
    // Remove orphan close tags for all tags that Confluence's XHTML parser enforces.
    // Order matters: process outer tags before inner ones.
    const TAGS: &[&str] = &[
        "div", "section",
        "p",
        "strong", "em", "span", "b", "i", "s", "u", "code",
    ];
    remove_orphan_close_tags(html, TAGS)
}

/// Minimal HTML-escape for cell values pushed into storage format.
fn escape_html(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// Convert scenario text to Confluence HTML.
/// Any Jira issue URL (https://.../browse/KEY-123) is turned into a Jira macro.
/// Non-URL text on other lines is emitted as a plain <p>.
fn scenario_to_html(scenario: &str, jira_server_id: Option<&str>) -> String {
    let url_re = regex::Regex::new(r"https?://[^\s]+/browse/([A-Z][A-Z0-9_]+-\d+)").unwrap();
    let mut html = String::new();
    for line in scenario.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() { continue; }
        if let Some(cap) = url_re.captures(trimmed) {
            let issue_key = &cap[1];
            let server_id = jira_server_id.unwrap_or("jira");
            html.push_str(&format!(
                r#"<p><ac:structured-macro ac:name="jira"><ac:parameter ac:name="server">System JIRA</ac:parameter><ac:parameter ac:name="serverId">{server_id}</ac:parameter><ac:parameter ac:name="key">{issue_key}</ac:parameter></ac:structured-macro></p>"#,
            ));
        } else {
            html.push_str(&format!("<p>{}</p>", escape_html(trimmed)));
        }
    }
    if html.is_empty() {
        html.push_str(&format!("<p>{}</p>", escape_html(scenario)));
    }
    html
}

/// Convert steps/expected-result text into a Confluence XHTML list.
/// Mirrors the Electron `toListItems(text, format, plainLinesAsBullets=true)`:
///   - all lines numbered ("1. " / "1) ") → `<ol>`
///   - all lines bulleted ("- " / "* " / "• ") → `<ul>`
///   - otherwise (plain lines) → `<ul>` with each line as a bullet
fn text_to_list_html(text: &str) -> String {
    let trimmed = text.trim();
    if trimmed.is_empty() {
        return String::new();
    }

    // Split into non-empty lines.
    let lines: Vec<&str> = trimmed.lines().map(|s| s.trim()).filter(|s| !s.is_empty()).collect();

    let numbered_re = regex::Regex::new(r"^\d+[.)]\s+").unwrap();
    let bullet_re   = regex::Regex::new(r"^[-*•]\s+").unwrap();

    let is_numbered = lines.iter().all(|l| numbered_re.is_match(l));
    let is_bullet   = lines.iter().all(|l| bullet_re.is_match(l));

    if is_numbered {
        let mut html = String::from("<ol>");
        for line in &lines {
            let content = numbered_re.replace(line, "");
            html.push_str(&format!("<li>{}</li>", escape_html(content.trim())));
        }
        html.push_str("</ol>");
        return html;
    }

    if is_bullet {
        let mut html = String::from("<ul>");
        for line in &lines {
            let content = bullet_re.replace(line, "");
            html.push_str(&format!("<li>{}</li>", escape_html(content.trim())));
        }
        html.push_str("</ul>");
        return html;
    }

    // Legacy inline format: "- 1. foo - 2. bar" (single line with separators).
    let inline_re = regex::Regex::new(r"(?:^|\s)-\s*\d+\.\s*").unwrap();
    let parts: Vec<&str> = inline_re.split(trimmed).map(|s| s.trim()).filter(|s| !s.is_empty()).collect();
    if parts.len() > 1 {
        let mut html = String::from("<ol>");
        for part in &parts {
            html.push_str(&format!("<li>{}</li>", escape_html(part)));
        }
        html.push_str("</ol>");
        return html;
    }

    // Plain lines — render each as a bullet (main branch's plainLinesAsBullets=true).
    let mut html = String::from("<ul>");
    for line in &lines {
        html.push_str(&format!("<li>{}</li>", escape_html(line)));
    }
    html.push_str("</ul>");
    html
}

/// Normalize a field label from a vertical-format table row (left column).
fn normalise_field_label(raw: &str) -> String {
    strip_inner_tags(raw).trim().to_lowercase()
}

/// Detect whether a table uses the vertical (card) format used by Documentation Sync,
/// where each row is: | Field Label | Value | and field labels match known QA fields.
fn is_vertical_table(body: &str) -> bool {
    let row_re = regex::Regex::new(r"(?is)<tr\b[^>]*>([\s\S]*?)</tr>").unwrap();
    let cell_re = regex::Regex::new(r"(?is)<t[dh][^>]*>([\s\S]*?)</t[dh]>").unwrap();
    let known: &[&str] = &[
        "no. test case", "no test case", "no. tc", "function", "scenario",
        "kategori", "input data", "steps", "test steps", "expected result",
        "result", "screen capture",
    ];
    let mut matched = 0usize;
    let mut checked = 0usize;
    for row_cap in row_re.captures_iter(body) {
        let cells: Vec<String> = cell_re
            .captures_iter(&row_cap[1])
            .map(|c| normalise_field_label(&c[1]))
            .collect();
        if cells.len() >= 1 {
            checked += 1;
            let label = cells[0].as_str();
            if known.iter().any(|k| label.contains(k)) {
                matched += 1;
            }
        }
        if checked >= 6 {
            break;
        }
    }
    checked > 0 && matched >= 3
}

/// Extract scenario text from a Confluence cell, mirroring the Electron
/// `extractTextValue` + `cleanConfluenceMacros`: each Jira macro is replaced by
/// its issue key while surrounding summary text is preserved.
/// e.g. `<p>Login <ac:structured-macro jira key="TRALOS-1"/>…</p>` → `Login TRALOS-1`.
fn extract_scenario_text(raw: &str) -> String {
    // Replace full <ac:structured-macro ac:name="jira">…</ac:structured-macro>
    // blocks with their issue key (keeps surrounding text).
    let macro_re = regex::Regex::new(
        r#"(?is)<ac:structured-macro\b[^>]*\bac:name\s*=\s*"jira"[^>]*>.*?</ac:structured-macro>"#,
    )
    .unwrap();
    let key_re = regex::Regex::new(
        r#"(?is)<ac:parameter\b[^>]*\bac:name\s*=\s*"key"[^>]*>([\s\S]*?)</ac:parameter>"#,
    )
    .unwrap();
    let cleaned = macro_re.replace_all(raw, |caps: &regex::Captures| {
        let keys: Vec<String> = key_re
            .captures_iter(&caps[0])
            .map(|c| strip_inner_tags(&c[1]).trim().to_string())
            .filter(|s| !s.is_empty())
            .collect();
        if keys.is_empty() {
            String::new()
        } else {
            keys.join(", ")
        }
    });
    let text = strip_inner_tags(&cleaned);
    if text.trim().is_empty() {
        // No jira macro found — plain text fallback.
        strip_inner_tags(raw).trim().to_string()
    } else {
        text.trim().to_string()
    }
}

/// Extract attachment filenames from a Confluence cell.
/// Handles both direct <ri:attachment ri:filename="..."/> and
/// filenames wrapped inside Expand macros or other nested structures.
/// Also handles single-quoted attribute values.
fn extract_attachment_filenames(raw: &str) -> Vec<String> {
    // Match ri:filename with double or single quotes
    let re = regex::Regex::new(
        r#"(?i)<ri:attachment\b[^>]*\bri:filename\s*=\s*(?:"([^"]+)"|'([^']+)')"#,
    )
    .unwrap();
    re.captures_iter(raw)
        .map(|c| {
            c.get(1)
                .or_else(|| c.get(2))
                .map(|m| m.as_str().to_string())
                .unwrap_or_default()
        })
        .filter(|s| !s.is_empty())
        .collect()
}

/// Split a table row's raw HTML into individual cell raw HTML contents.
/// Uses a simple open/close counter to handle nested tags inside cells.
fn split_row_cells(row_html: &str) -> Vec<String> {
    let mut cells = Vec::new();
    let open_re = regex::Regex::new(r"(?i)<(td|th)\b[^>]*>").unwrap();
    let close_re = regex::Regex::new(r"(?i)</(td|th)>").unwrap();
    let len = row_html.len();
    let mut pos = 0usize;

    while pos < len {
        let Some(open_cap) = open_re.find(&row_html[pos..]) else { break };
        let cell_start = pos + open_cap.end();
        let mut depth = 1i32;
        let mut cur = cell_start;
        while cur < len && depth > 0 {
            let rest = &row_html[cur..];
            let next_open = open_re.find(rest).map(|m| m.start());
            let next_close = close_re.find(rest).map(|m| m.start());
            match (next_open, next_close) {
                (Some(o), Some(c)) if o < c => {
                    depth += 1;
                    cur += open_re.find(rest).unwrap().end();
                }
                (_, Some(c)) => {
                    depth -= 1;
                    let close_end = cur + close_re.find(rest).unwrap().end();
                    if depth == 0 {
                        cells.push(row_html[cell_start..cur + c].to_string());
                        cur = close_end;
                        break;
                    }
                    cur = close_end;
                }
                _ => break,
            }
        }
        if cur <= cell_start { break; }
        pos = cur;
    }
    cells
}

/// Find the position of "Screen Capture" label row in the table body,
/// then extract ALL ri:attachment filenames from the rest of the table body
/// after that label — this handles Expand macros that contain </tr> inside them.
fn extract_screen_capture_filenames_from_body(body: &str) -> Vec<String> {
    // Find where the Screen Capture label appears (case-insensitive plain text)
    let lower = body.to_lowercase();
    let marker_pos = lower
        .find("screen capture")
        .or_else(|| lower.find("screenshot"))
        .or_else(|| lower.find("screen shot"));

    if let Some(pos) = marker_pos {
        // Search for ri:attachment anywhere after the marker in the full body
        extract_attachment_filenames(&body[pos..])
    } else {
        Vec::new()
    }
}

/// Parse a vertical-format table (one test case per table block).
/// Rows: | Field Label | Value |
fn parse_vertical_table(body: &str, counter: &mut usize) -> Option<ConfluenceTestImportEntry> {
    let mut test_case_no = String::new();
    let mut function_name = String::new();
    let mut scenario = String::new();
    let mut steps = String::new();
    let mut expected_result = String::new();
    let mut input_data = String::new();
    let mut found_any = false;

    for (_rs, _re, inner_start, inner_end) in iter_tr_positions(body) {
        let row_inner = &body[inner_start..inner_end];
        // Use depth-aware cell splitter to handle nested tags inside cells
        let raw_cells = split_row_cells(row_inner);
        if raw_cells.len() < 2 {
            continue;
        }
        let label = strip_inner_tags(&raw_cells[0]).trim().to_lowercase();
        let raw_value = &raw_cells[1];

        if label.contains("no. test case") || label.contains("no test case") || label.contains("no. tc") || label == "no tc" {
            test_case_no = strip_inner_tags(raw_value).trim().to_string();
            found_any = true;
        } else if label.contains("function") {
            function_name = strip_inner_tags(raw_value).trim().to_string();
            found_any = true;
        } else if label.contains("scenario") {
            scenario = extract_scenario_text(raw_value);
            found_any = true;
        } else if label.contains("input data") {
            input_data = extract_text_lines(raw_value);
            found_any = true;
        } else if label.contains("steps") || label.contains("langkah") {
            steps = extract_text_lines(raw_value);
            found_any = true;
        } else if label.contains("expected") || label.contains("hasil yang diharapkan") {
            expected_result = extract_text_lines(raw_value);
            found_any = true;
        }
    }

    // Extract screen capture filenames from the full table body (bypasses lazy </tr> truncation)
    // This correctly handles Expand macros that embed </tr> inside their body.
    let screen_capture_filenames = extract_screen_capture_filenames_from_body(body);

    if !found_any {
        return None;
    }

    let id = format!("tc-{}", counter);
    *counter += 1;
    Some(ConfluenceTestImportEntry {
        id,
        issue_key: String::new(),
        test_case_no,
        function_name,
        scenario,
        input_data,
        steps,
        expected_result,
        selected: true,
        source_table_index: None,
        screen_capture_filenames,
        images: Vec::new(), // populated later by parse_confluence_entries
    })
}

static RE_TABLE: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
static RE_ROW: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
static RE_CELL: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
static RE_TH: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
static RE_TH_CELL: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();

/// Parse every `<table>` in a storage body into import entries.
