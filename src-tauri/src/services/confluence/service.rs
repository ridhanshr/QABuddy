//! Confluence service — held in app state. P3 wires connection testing + page
//! access; this module (P5b) adds page preview, attachment upload, page update,
//! Jira server-id detection, table generation, and Confluence-entry parsing.
//!
//! The HTML storage-format manipulation (XHTML tables, TOC macros, generated
//! markers) mirrors the Electron `confluence-service.ts` + `table-formatter.ts`
//! behaviour, ported to Rust regex.

use base64::Engine as _;
use serde_json::Value;

use crate::models::app_config::ConfluenceConfig;
use crate::models::jira::ConfluenceTestImportEntry;
use crate::models::misc::{
    ConfluenceParseProgress, ParseConfluenceEntriesOptions, ParseConfluenceEntriesResult,
    SyncToConfluencePayload, SyncToConfluenceResult,
};
use crate::services::confluence::client::ConfluenceClient;
use crate::services::error::Result;
use crate::services::http::normalize_url;
use tauri::{AppHandle, Emitter};

pub struct ConfluenceService;

impl ConfluenceService {
    pub fn new() -> Self {
        Self
    }

    fn client(&self, config: &ConfluenceConfig) -> ConfluenceClient {
        ConfluenceClient::new(config)
    }

    /// Probe Confluence connectivity; returns a status string.
    pub async fn test_connection(&self, config: &ConfluenceConfig) -> Result<String> {
        self.client(config).validate_connection().await
    }

    /// Fetch a raw Confluence page document.
    pub async fn get_page(&self, config: &ConfluenceConfig, page_id: &str) -> Result<Value> {
        self.client(config).get_page(page_id).await
    }

    /// Resolve a user-facing Confluence URL to a page document.
    pub async fn get_page_by_url(&self, config: &ConfluenceConfig, url: &str) -> Result<Value> {
        self.client(config).get_page_by_url(url).await
    }

    /// List pages for a space key or ancestor/page id. Used by RAG indexing.
    pub async fn list_pages(&self, config: &ConfluenceConfig, space_or_page_id: &str) -> Result<Vec<Value>> {
        self.client(config).list_pages(space_or_page_id).await
    }

    pub async fn get_attachments(&self, config: &ConfluenceConfig, page_id: &str) -> Result<Vec<Value>> {
        self.client(config).get_attachments(page_id).await
    }

    pub async fn download_attachment(&self, config: &ConfluenceConfig, download_path: &str) -> Result<Vec<u8>> {
        self.client(config).download_attachment(download_path).await
    }

    /// Lightweight page preview: title, storage body, version.
    pub async fn get_page_preview(
        &self,
        config: &ConfluenceConfig,
        page_id: &str,
    ) -> Result<(String, String, u32)> {
        let page = self.get_page(config, page_id).await?;
        let title = page["title"].as_str().unwrap_or("").to_string();
        let content = page["body"]["storage"]["value"]
            .as_str()
            .unwrap_or("")
            .to_string();
        let version = page["version"]["number"].as_u64().unwrap_or(1) as u32;
        Ok((title, content, version))
    }

    /// Resolve the Jira application-link server id from Confluence applinks.
    pub async fn detect_jira_server_id(&self, config: &ConfluenceConfig) -> Result<Option<String>> {
        Ok(self.client(config).detect_jira_server_id().await)
    }

    pub async fn upload_attachment(
        &self,
        config: &ConfluenceConfig,
        page_id: &str,
        filename: &str,
        data: Vec<u8>,
    ) -> Result<Value> {
        self.client(config)
            .upload_attachment(page_id, filename, data)
            .await
    }

    pub async fn update_page(
        &self,
        config: &ConfluenceConfig,
        page_id: &str,
        title: &str,
        content: &str,
        version: u32,
    ) -> Result<Value> {
        self.client(config)
            .update_page(page_id, title, content, version)
            .await
    }

    fn emit_parse_progress(
        app_handle: Option<&AppHandle>,
        stage: &str,
        message: impl Into<String>,
        current: usize,
        total: usize,
        detail: Option<String>,
    ) {
        if let Some(handle) = app_handle {
            let _ = handle.emit(
                "confluence-parse-progress",
                ConfluenceParseProgress {
                    stage: stage.to_string(),
                    message: message.into(),
                    current,
                    total,
                    detail,
                },
            );
        }
    }

    // ── Storage-format helpers ──────────────────────────────────────────

    /// Strip only our own "Generated by QA Buddy" trailer markers.
    /// Does NOT touch TOC macros, h1, or any other page content — those belong
    /// to the page owner and must be preserved exactly as fetched.
    fn strip_generated_markers(content: &str) -> String {
        let gen = regex::Regex::new(
            r#"(?i)\s*<p>\s*Generated by QA Buddy\s*[-—]\s*[^<]+</p>\s*"#,
        )
        .unwrap();
        let gen_simple = regex::Regex::new(
            r#"(?i)\s*<p>\s*Generated by QA Buddy\s*</p>\s*"#,
        )
        .unwrap();
        let mut out = gen.replace_all(content, "").to_string();
        out = gen_simple.replace_all(&out, "").to_string();
        out
    }

    /// Map category value from QA Buddy to Confluence display label.
    fn category_label(category: &str) -> &'static str {
        match category.trim().to_uppercase().as_str() {
            "TC_REGRESSION" | "REGRESSION" | "REGRESI" => "Regresi",
            "TC_UNHAPPY" | "UNHAPPY" | "NEGATIVE" => "Negative",
            "TC_HAPPY" | "HAPPY" | "POSITIVE" => "Positive",
            _ => "Positive",
        }
    }

    /// Build the HTML for a single Result cell — plain text, no colour.
    fn result_cell_html(result: &str) -> String {
        let label = match result.trim().to_uppercase().as_str() {
            "PASS" | "PASSED" => "Passed",
            "FAIL" | "FAILED" => "Failed",
            other if other.is_empty() => "",
            _ => result.trim(),
        };
        if label.is_empty() {
            String::new()
        } else {
            format!("<p>{}</p>", escape_html(label))
        }
    }

    /// Build the Screen Capture cell HTML: one Expand macro containing all images.
    fn screen_capture_cell_html(
        entry_id: &str,
        images: &[serde_json::Value],
        uploaded: &std::collections::HashMap<(String, String), String>,
    ) -> String {
        let mut sorted = images.to_vec();
        sorted.sort_by_key(|img| img["order"].as_u64().unwrap_or(0));

        // Group images by expandGroup, preserving insertion order of groups.
        let mut group_order: Vec<String> = Vec::new();
        let mut groups: std::collections::HashMap<String, Vec<&serde_json::Value>> =
            std::collections::HashMap::new();
        for img in &sorted {
            let group = img["expandGroup"].as_str().unwrap_or("").trim().to_string();
            if !groups.contains_key(&group) {
                group_order.push(group.clone());
            }
            groups.entry(group).or_default().push(img);
        }

        let mut all_expands = String::new();
        for group_key in &group_order {
            let imgs = &groups[group_key];
            let expand_title = if group_key.is_empty() {
                "Click here to expand...".to_string()
            } else {
                escape_html(group_key)
            };

            let mut inner = String::new();
            for img in imgs.iter() {
                let orig_name = img["name"].as_str().unwrap_or("").to_string();
                let note = img["note"].as_str().unwrap_or("").trim().to_string();
                let key = (entry_id.to_string(), orig_name);
                if let Some(uploaded_name) = uploaded.get(&key) {
                    if !note.is_empty() {
                        inner.push_str(&format!(
                            r#"<p><strong>{}</strong></p>"#,
                            escape_html(&note)
                        ));
                    }
                    inner.push_str(&format!(
                        r#"<p><ac:image ac:width="450"><ri:attachment ri:filename="{}" /></ac:image></p>"#,
                        escape_html(uploaded_name)
                    ));
                }
            }

            if !inner.is_empty() {
                all_expands.push_str(&format!(
                    r#"<ac:structured-macro ac:name="expand"><ac:parameter ac:name="title">{}</ac:parameter><ac:rich-text-body>{}</ac:rich-text-body></ac:structured-macro>"#,
                    expand_title, inner
                ));
            }
        }

        all_expands
    }

    /// Update existing vertical-card tables in `content` in-place.
    ///
    /// Strategy: scan for every `<table>…</table>` block; if it is a vertical
    /// table whose "No. Test Case" row value matches one of the payload entries,
    /// replace the value cells for all known fields with the new data.
    /// Returns the mutated content and a set of entry IDs that were matched.
    fn patch_existing_tables(
        content: &str,
        entries: &[serde_json::Value],
        uploaded: &std::collections::HashMap<(String, String), String>,
        jira_server_id: Option<&str>,
    ) -> (String, std::collections::HashSet<String>) {
        // Build lookup by sourceTableIndex → entry (primary, matches parse order).
        let mut by_source: std::collections::HashMap<usize, &serde_json::Value> =
            std::collections::HashMap::new();
        for entry in entries {
            if let Some(idx) = entry["sourceTableIndex"].as_u64() {
                by_source.insert(idx as usize, entry);
            }
        }

        // Build lookup: composite key (testCaseNo + "|" + functionName) → entry
        // (fallback for entries without sourceTableIndex, e.g. manually added).
        let mut by_tc: std::collections::HashMap<String, &serde_json::Value> =
            std::collections::HashMap::new();
        for entry in entries {
            let tc  = entry["testCaseNo"].as_str().unwrap_or("").trim().to_lowercase();
            let fun = entry["functionName"].as_str().unwrap_or("").trim().to_lowercase();
            if !tc.is_empty() {
                // Primary key: tc + function (exact match across sub-sections)
                by_tc.insert(format!("{tc}|{fun}"), entry);
                // Fallback key: tc alone (used only if no function match found — see below)
                by_tc.entry(tc).or_insert(entry);
            }
        }

        let mut matched_ids: std::collections::HashSet<String> = std::collections::HashSet::new();

        // Collect all table positions first, then build result in one forward pass
        // so we never need offset tracking (which breaks when replacements shrink content).
        let table_positions = iter_table_positions(content);

        // For each table position, decide what to emit: original or patched
        struct Patch { tbl_start: usize, tbl_end: usize, replacement: String, entry_id: String }
        let mut patches: Vec<Patch> = Vec::new();

        // Mirrors the parse step: only vertical-card tables get a sourceTableIndex.
        let mut vertical_index = 0usize;

        for (tbl_start, tbl_end) in table_positions {
            let original_table = &content[tbl_start..tbl_end];

            if !is_vertical_table(original_table) {
                continue;
            }
            // Only tables the parser would count as import entries advance the index.
            let mut dummy = 0usize;
            if parse_vertical_table(original_table, &mut dummy).is_none() {
                continue;
            }
            let my_index = vertical_index;
            vertical_index += 1;

            // Prefer the exact sourceTableIndex match (updates the same table in place).
            let entry = by_source.get(&my_index).copied();
            let entry = match entry {
                Some(e) => Some(e),
                None => {
                    let tc_val = extract_vertical_cell(original_table, "no. test case")
                        .or_else(|| extract_vertical_cell(original_table, "no test case"))
                        .or_else(|| extract_vertical_cell(original_table, "no. tc"))
                        .unwrap_or_default();
                    let tc_key = tc_val.trim().to_lowercase();
                    if tc_key.is_empty() { continue; }

                    let fun_val = extract_vertical_cell(original_table, "function")
                        .or_else(|| extract_vertical_cell(original_table, "function name"))
                        .unwrap_or_default();
                    let fun_key = fun_val.trim().to_lowercase();

                    // Try composite key first; fall back to tc-only if function not present
                    let composite = format!("{tc_key}|{fun_key}");
                    if let Some(e) = by_tc.get(&composite) {
                        Some(*e)
                    } else if !fun_key.is_empty() {
                        // No composite match — this table belongs to a different sub-section
                        None
                    } else if let Some(e) = by_tc.get(&tc_key) {
                        Some(*e)
                    } else {
                        None
                    }
                }
            };
            let Some(entry) = entry else { continue };

            let entry_id = entry["id"].as_str().unwrap_or("").to_string();
            let images = entry["images"].as_array().cloned().unwrap_or_default();

            let category_html = format!("<p>{}</p>", escape_html(Self::category_label(entry["category"].as_str().unwrap_or(""))));
            let replacements: Vec<(&str, String)> = vec![
                ("function",        format!("<p>{}</p>", escape_html(entry["functionName"].as_str().unwrap_or("")))),
                ("scenario",        scenario_to_html(entry["scenario"].as_str().unwrap_or(""), jira_server_id)),
                ("kategori",        category_html.clone()),
                ("category",        category_html),
                ("input data",      text_to_list_html(entry["inputData"].as_str().unwrap_or(""))),
                ("steps",           text_to_list_html(entry["steps"].as_str().unwrap_or(""))),
                ("expected result", text_to_list_html(entry["expectedResult"].as_str().unwrap_or(""))),
                ("result",          Self::result_cell_html(entry["result"].as_str().unwrap_or(""))),
                ("screen capture",  Self::screen_capture_cell_html(&entry_id, &images, uploaded)),
            ];

            let mut new_table = original_table.to_string();
            for (label, new_value) in &replacements {
                new_table = replace_vertical_cell_value(&new_table, label, new_value);
            }

            if new_table != original_table {
                patches.push(Patch { tbl_start, tbl_end, replacement: new_table, entry_id });
            }
        }

        // Build the final string in a single forward pass over the original content
        let mut result = String::with_capacity(content.len() + 1024);
        let mut cursor = 0usize;
        for patch in &patches {
            result.push_str(&content[cursor..patch.tbl_start]);
            result.push_str(&patch.replacement);
            cursor = patch.tbl_end;
            matched_ids.insert(patch.entry_id.clone());
        }
        result.push_str(&content[cursor..]);

        (result, matched_ids)
    }

    /// Generate vertical-card XHTML tables for entries that had no match in
    /// the existing page content (append-only path).
    pub fn generate_vertical_tables(
        entries: &[serde_json::Value],
        uploaded: &std::collections::HashMap<(String, String), String>,
        jira_server_id: Option<&str>,
    ) -> String {
        let mut html = String::new();
        for entry in entries {
            let id            = entry["id"].as_str().unwrap_or("").to_string();
            let test_case_no  = entry["testCaseNo"].as_str().unwrap_or("").to_string();
            let function_name = entry["functionName"].as_str().unwrap_or("").to_string();
            let scenario      = entry["scenario"].as_str().unwrap_or("").to_string();
            let category      = Self::category_label(entry["category"].as_str().unwrap_or(""));
            let input_data    = entry["inputData"].as_str().unwrap_or("").to_string();
            let steps         = entry["steps"].as_str().unwrap_or("").to_string();
            let expected      = entry["expectedResult"].as_str().unwrap_or("").to_string();
            let result        = entry["result"].as_str().unwrap_or("").to_string();
            let images        = entry["images"].as_array().cloned().unwrap_or_default();

            let screen_capture_html = Self::screen_capture_cell_html(&id, &images, uploaded);
            let result_html         = Self::result_cell_html(&result);
            let scenario_html       = scenario_to_html(&scenario, jira_server_id);

            html.push_str(r#"<table class="wrapped confluenceTable"><colgroup><col style="width: 200px;"/><col/></colgroup><tbody>"#);
            html.push_str(&format!("<tr><th class=\"confluenceTh\">No. Test Case</th><td class=\"confluenceTd\"><p>{}</p></td></tr>", escape_html(&test_case_no)));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Function</th><td class=\"confluenceTd\"><p>{}</p></td></tr>", escape_html(&function_name)));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Scenario</th><td class=\"confluenceTd\">{scenario_html}</td></tr>"));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Kategori</th><td class=\"confluenceTd\"><p>{}</p></td></tr>", escape_html(category)));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Input Data</th><td class=\"confluenceTd\">{}</td></tr>", text_to_list_html(&input_data)));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Steps</th><td class=\"confluenceTd\">{}</td></tr>", text_to_list_html(&steps)));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Expected Result</th><td class=\"confluenceTd\">{}</td></tr>", text_to_list_html(&expected)));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Result</th><td class=\"confluenceTd\">{}</td></tr>", result_html));
            html.push_str(&format!("<tr><th class=\"confluenceTh\">Screen Capture</th><td class=\"confluenceTd\">{}</td></tr>", screen_capture_html));
            html.push_str("</tbody></table><p>&nbsp;</p>");
        }
        html
    }

    /// Generate a single XHTML `<table>` from import entries (one row each).
    /// Columns: TestCase No | Function Name | Scenario | Steps | Expected Result.
    /// Kept for parse roundtrip tests only — sync now uses generate_vertical_tables.
    pub fn generate_single_table(entries: &[ConfluenceTestImportEntry]) -> String {
        let mut html = String::from(
            "<table class=\"wrapped confluenceTable\"><colgroup><col/><col/><col/><col/><col/></colgroup>",
        );
        html.push_str("<tbody>");
        html.push_str(
            "<tr><th class=\"confluenceTh\">TestCase No</th><th class=\"confluenceTh\">Function Name</th><th class=\"confluenceTh\">Scenario</th><th class=\"confluenceTh\">Steps</th><th class=\"confluenceTh\">Expected Result</th></tr>",
        );
        for entry in entries {
            html.push_str(&format!(
                "<tr><td class=\"confluenceTd\">{}</td><td class=\"confluenceTd\">{}</td><td class=\"confluenceTd\">{}</td><td class=\"confluenceTd\">{}</td><td class=\"confluenceTd\">{}</td></tr>",
                escape_html(&entry.test_case_no),
                escape_html(&entry.function_name),
                escape_html(&entry.scenario),
                escape_html(&entry.steps),
                escape_html(&entry.expected_result),
            ));
        }
        html.push_str("</tbody></table>");
        html
    }

    // ── High-level operations ───────────────────────────────────────────

    /// Sync entries into a Confluence page.
    ///
    /// If the page already has vertical-card tables whose "No. Test Case" value
    /// matches a payload entry, those tables are updated **in-place** (no new
    /// table is created).  Entries with no matching table are appended at the end.
    /// Images are uploaded as attachments and referenced in a single Expand macro.
    pub async fn sync_to_confluence(
        &self,
        config: &ConfluenceConfig,
        page_id: &str,
        payload: &SyncToConfluencePayload,
    ) -> Result<SyncToConfluenceResult> {
        let (title, raw_content, version) = self.get_page_preview(config, page_id).await?;
        let content = sanitize_confluence_storage_html(&raw_content);

        let entry_count = payload.entries.len() as u32;

        // ── 1. Check existing attachments to skip redundant uploads ──────
        let existing_attachments = self.get_attachments(config, page_id).await.unwrap_or_default();
        let existing_filenames: std::collections::HashSet<String> = existing_attachments
            .iter()
            .filter_map(|a| a["title"].as_str().map(|s| s.to_string()))
            .collect();

        // ── 2. Collect image upload tasks ────────────────────────────────
        let mut uploaded: std::collections::HashMap<(String, String), String> =
            std::collections::HashMap::new();
        let mut total_images = 0u32;

        struct UploadTaskItem {
            entry_id: String,
            orig_name: String,
            upload_name: String,
            bytes: Vec<u8>,
        }

        let mut tasks_to_upload: Vec<UploadTaskItem> = Vec::new();

        for entry in &payload.entries {
            let entry_id = entry["id"].as_str().unwrap_or("").to_string();
            let images = entry["images"].as_array().cloned().unwrap_or_default();
            let mut sorted = images.clone();
            sorted.sort_by_key(|img| img["order"].as_u64().unwrap_or(0));

            for img in &sorted {
                let orig_name = img["name"].as_str().unwrap_or("attachment.png").to_string();
                if orig_name.is_empty() {
                    continue;
                }
                let data_uri = img["data"].as_str().unwrap_or("");

                // If an attachment with this exact name already lives on the
                // page, reuse it instead of re-uploading. After a parse the image
                // name IS the Confluence attachment title, so unchanged
                // attachments (only steps/expected edited) are never re-sent.
                if existing_filenames.contains(&orig_name) {
                    uploaded.insert((entry_id.clone(), orig_name.clone()), orig_name);
                    continue;
                }

                // Nothing to upload and nothing to reference.
                if data_uri.is_empty() {
                    continue;
                }

                let base64_data = if let Some(pos) = data_uri.find(',') {
                    &data_uri[pos + 1..]
                } else {
                    data_uri
                };
                let bytes = match base64::engine::general_purpose::STANDARD.decode(base64_data) {
                    Ok(b) => b,
                    Err(_) => continue,
                };

                let safe_entry = entry_id.replace(['/', '\\', ' '], "_");
                let upload_name = format!("{safe_entry}_{orig_name}");
                tasks_to_upload.push(UploadTaskItem {
                    entry_id: entry_id.clone(),
                    orig_name,
                    upload_name,
                    bytes,
                });
            }
        }

        // Run uploads concurrently (max 8 at a time)
        if !tasks_to_upload.is_empty() {
            let client = self.client(config);
            let sem = std::sync::Arc::new(tokio::sync::Semaphore::new(8));
            let mut join_set = tokio::task::JoinSet::new();
            let page_id_str = page_id.to_string();

            for item in tasks_to_upload {
                let client = client.clone();
                let sem = sem.clone();
                let page_id_clone = page_id_str.clone();

                join_set.spawn(async move {
                    let _permit = sem.acquire().await;
                    let res = client
                        .upload_attachment(&page_id_clone, &item.upload_name, item.bytes)
                        .await;
                    (item.entry_id, item.orig_name, item.upload_name, res.is_ok())
                });
            }

            while let Some(res) = join_set.join_next().await {
                if let Ok((entry_id, orig_name, upload_name, success)) = res {
                    if success {
                        uploaded.insert((entry_id, orig_name), upload_name);
                        total_images += 1;
                    }
                }
            }
        }

        // ── 3. Patch existing tables in-place ────────────────────────────
        let jira_server_id = config.jira_server_id.as_deref();
        let (mut content, matched_ids) =
            Self::patch_existing_tables(&content, &payload.entries, &uploaded, jira_server_id);

        // ── 4. Append tables for entries not found in existing content ───
        let new_entries: Vec<&serde_json::Value> = payload
            .entries
            .iter()
            .filter(|e| {
                let id = e["id"].as_str().unwrap_or("");
                !matched_ids.contains(id)
            })
            .collect();

        if !new_entries.is_empty() {
            // Remove the "Generated by QA Buddy" trailer if present so we append before it
            content = Self::strip_generated_markers(&content);
            let jira_server_id = config.jira_server_id.as_deref();
            let new_tables = Self::generate_vertical_tables(
                &new_entries.into_iter().cloned().collect::<Vec<_>>(),
                &uploaded,
                jira_server_id,
            );
            content.push_str(&new_tables);
        }

        // ── 5. Repair any unclosed inline tags left over from the original page ─
        let content = close_unclosed_inline_tags(&content);

        // ── 6. Write back to Confluence ──────────────────────────────────
        let updated = self.update_page(config, page_id, &title, &content, version).await?;
        let page_url = updated
            .get("_links")
            .and_then(|l| l.get("base"))
            .and_then(|b| b.as_str())
            .map(|b| format!(
                "{}/pages/viewpage.action?pageId={page_id}",
                normalize_url(b)
            ))
            .unwrap_or_else(|| format!("/pages/viewpage.action?pageId={page_id}"));

        Ok(SyncToConfluenceResult {
            page_title: title,
            page_url,
            entry_count,
            image_count: total_images,
            attachment_count: total_images,
        })
    }

    /// Parse a Confluence page's storage body into import entries. Each
    /// `<table>` whose first row has header cells is treated as a set of test
    /// rows; columns are mapped to ConfluenceTestImportEntry fields by header.
    pub async fn parse_confluence_entries(
        &self,
        app_handle: Option<&AppHandle>,
        config: &ConfluenceConfig,
        page_id: &str,
        options: &ParseConfluenceEntriesOptions,
    ) -> Result<ParseConfluenceEntriesResult> {
        Self::emit_parse_progress(
            app_handle,
            "fetch_page",
            "Memuat halaman Confluence",
            0,
            1,
            Some(format!("Page ID: {page_id}")),
        );
        let (title, content, _version) = match self.get_page_preview(config, page_id).await {
            Ok(t) => (Some(t.0), t.1, t.2),
            Err(e) => {
                Self::emit_parse_progress(
                    app_handle,
                    "error",
                    "Gagal memuat halaman Confluence",
                    0,
                    1,
                    Some(e.to_string()),
                );
                return Ok(ParseConfluenceEntriesResult {
                    page_id: page_id.to_string(),
                    page_title: String::new(),
                    content_loaded: false,
                    entries: vec![],
                    jira_server_id: None,
                    error: Some(e.to_string()),
                    debug: None,
                });
            }
        };
        Self::emit_parse_progress(
            app_handle,
            "fetch_page",
            "Halaman Confluence berhasil dimuat",
            1,
            1,
            title.clone(),
        );
        let table_positions = iter_table_positions(&content);
        let total_tables = table_positions.len();
        Self::emit_parse_progress(
            app_handle,
            "parse_tables",
            "Mulai parsing tabel",
            0,
            total_tables,
            Some(format!("{total_tables} tabel terdeteksi")),
        );
        let mut entries = parse_tables_to_entries_with_progress(&content, Some(&table_positions), |current, total| {
            Self::emit_parse_progress(
                app_handle,
                "parse_tables",
                format!("Parsing tabel {current} / {total}"),
                current,
                total,
                None,
            );
        });
        let jira_server_id = if options.include_jira_server_id {
            Self::emit_parse_progress(
                app_handle,
                "detect_jira",
                "Mendeteksi Jira Server ID",
                0,
                1,
                None,
            );
            let detected = self.client(config).detect_jira_server_id().await;
            Self::emit_parse_progress(
                app_handle,
                "detect_jira",
                "Deteksi Jira Server ID selesai",
                1,
                1,
                detected.clone(),
            );
            detected
        } else {
            None
        };

        // Download screen capture attachments concurrently for entries that need them
        let needs_images = options.include_images && entries.iter().any(|e| !e.screen_capture_filenames.is_empty());
        if needs_images {
            Self::emit_parse_progress(
                app_handle,
                "fetch_attachments",
                "Memuat attachment page",
                0,
                1,
                None,
            );
            // Fetch all page attachments once
            let all_attachments = self.get_attachments(config, page_id).await.unwrap_or_default();
            Self::emit_parse_progress(
                app_handle,
                "fetch_attachments",
                "Attachment page berhasil dimuat",
                1,
                1,
                Some(format!("{} attachment ditemukan", all_attachments.len())),
            );
            // Build filename → download_path map
            let att_map: std::collections::HashMap<String, String> = all_attachments
                .iter()
                .filter_map(|a| {
                    let name = a["title"].as_str()?.to_string();
                    let path = a["_links"]["download"].as_str()?.to_string();
                    Some((name, path))
                })
                .collect();

            struct DownloadTaskItem {
                entry_idx: usize,
                order: usize,
                filename: String,
                download_path: String,
            }

            let mut download_tasks: Vec<DownloadTaskItem> = Vec::new();
            for (entry_idx, entry) in entries.iter().enumerate() {
                for (order, filename) in entry.screen_capture_filenames.iter().enumerate() {
                    if let Some(download_path) = att_map.get(filename) {
                        download_tasks.push(DownloadTaskItem {
                            entry_idx,
                            order,
                            filename: filename.clone(),
                            download_path: download_path.clone(),
                        });
                    }
                }
            }

            if !download_tasks.is_empty() {
                let total_downloads = download_tasks.len();
                Self::emit_parse_progress(
                    app_handle,
                    "download_images",
                    "Mulai memproses image attachment",
                    0,
                    total_downloads,
                    None,
                );
                let client = self.client(config);
                let sem = std::sync::Arc::new(tokio::sync::Semaphore::new(8));
                let mut join_set = tokio::task::JoinSet::new();

                for item in download_tasks {
                    let client = client.clone();
                    let sem = sem.clone();

                    join_set.spawn(async move {
                        let _permit = sem.acquire().await;
                        let res = client.download_attachment(&item.download_path).await;
                        (item.entry_idx, item.order, item.filename, res)
                    });
                }

                let mut downloaded_map: std::collections::HashMap<
                    usize,
                    Vec<(usize, crate::models::jira::ConfluenceEntryImage)>,
                > = std::collections::HashMap::new();
                let mut processed = 0usize;

                while let Some(res) = join_set.join_next().await {
                    processed += 1;
                    Self::emit_parse_progress(
                        app_handle,
                        "download_images",
                        format!("Memproses image {processed} / {total_downloads}"),
                        processed,
                        total_downloads,
                        None,
                    );
                    if let Ok((entry_idx, order, filename, Ok(bytes))) = res {
                        let ext = filename.rsplit('.').next().unwrap_or("png").to_lowercase();
                        let mime = match ext.as_str() {
                            "jpg" | "jpeg" => "image/jpeg",
                            "gif" => "image/gif",
                            "webp" => "image/webp",
                            _ => "image/png",
                        };
                        let b64 = base64_encode(&bytes);
                        let img = crate::models::jira::ConfluenceEntryImage {
                            id: uuid::Uuid::new_v4().to_string(),
                            name: filename,
                            data: format!("data:{mime};base64,{b64}"),
                            order: order + 1,
                            note: String::new(),
                            expand_group: String::new(),
                        };
                        downloaded_map.entry(entry_idx).or_default().push((order, img));
                    }
                }

                for (entry_idx, mut list) in downloaded_map {
                    list.sort_by_key(|(order, _)| *order);
                    entries[entry_idx].images = list.into_iter().map(|(_, img)| img).collect();
                }
            }
        }

        Self::emit_parse_progress(
            app_handle,
            "done",
            format!("Selesai: {} entries ditemukan", entries.len()),
            entries.len(),
            entries.len(),
            title.clone(),
        );

        Ok(ParseConfluenceEntriesResult {
            page_id: page_id.to_string(),
            page_title: title.unwrap_or_default(),
            content_loaded: true,
            entries,
            jira_server_id,
            error: None,
            debug: None,
        })
    }
}

